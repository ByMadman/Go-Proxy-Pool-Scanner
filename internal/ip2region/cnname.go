// cnCountryName 返回国家/地区的中文名；无映射时原样返回。
func cnCountryName(name string) string {
	n := strings.TrimSpace(name)
	if n == "" {
		return ""
	}
	if cn, ok := countryCN[strings.ToLower(n)]; ok {
		return cn
	}
	return n
}
