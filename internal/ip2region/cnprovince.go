// normPlaceKey 归一化地名 key：小写 + 去掉组合附加符（İ → i 这类字符才能匹配）。
func normPlaceKey(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	var b strings.Builder
	b.Grow(len(s))
	for _, r := range s {
		if unicode.Is(unicode.Mn, r) {
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// provinceCNIndex 归一化后的查询表，避免每次比较都做字符串处理。
var provinceCNIndex = func() map[string]string {
	m := make(map[string]string, len(provinceCN))
	for k, v := range provinceCN {
		m[normPlaceKey(k)] = v
	}
	return m
}()

// cnProvinceName 返回省份/一级行政区的中文名；无映射时原样返回。
// code 用于区分同名地区（US 的 Georgia 与格鲁吉亚）。
func cnProvinceName(code, name string) string {
	n := strings.TrimSpace(name)
	if n == "" {
		return ""
	}
	if cn, ok := provinceCNIndex[normPlaceKey(code+"|"+n)]; ok {
		return cn
	}
	return n
}
